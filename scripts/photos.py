"""Builds the bundled destination and vehicle photos.

Input: a folder of source JPEGs named <slug>.jpg (downloaded from Wikimedia Commons) and a meta.json with each
file's Commons title, page, author and license. Output: WebP files at up to three widths in public/images/photos
(never upscaled), a tiny blurred preview per photo, and src/seed/photoData.ts with the credits.

    python3 scripts/photos.py <source-folder> <meta.json>
"""
import base64, io, json, os, re, sys
from PIL import Image, ImageFilter

WIDTHS = [480, 960, 1600]
OUT = os.path.join(os.path.dirname(__file__), '..', 'public', 'images', 'photos')
DATA = os.path.join(os.path.dirname(__file__), '..', 'src', 'seed', 'photoData.ts')

# Where the subject sits, for object-position when a frame crops the photo. Defaults to the centre.
FOCUS = {
    'baguio': '50% 62%', 'vigan': '38% 60%', 'launion': '40% 45%', 'hundred-islands': '55% 60%', 'baler': '62% 55%', 'sagada': '45% 40%',
    'banaue': '55% 50%', 'tagaytay': '60% 55%', 'batangas': '65% 60%', 'cavinti': '55% 55%',
    'intramuros': '50% 55%', 'minalungao': '55% 60%', 'tanay': '50% 55%', 'bolinao': '50% 50%', 'dingalan': '45% 55%',
    'lucban': '45% 50%', 'van-hiace': '55% 60%', 'van-staria': '60% 60%', 'pinatubo': '60% 55%', 'subic': '40% 55%', 'pampanga': '45% 45%', 'bataan': '55% 55%', 'taal-town': '50% 40%',
}


def credit_title(title):
    t = re.sub(r'^File:', '', title)
    t = re.sub(r'\.(jpe?g)$', '', t, flags=re.I)
    return t.replace('_', ' ')


def main(src, meta_path):
    meta = json.load(open(meta_path))
    os.makedirs(OUT, exist_ok=True)
    entries = {}
    for slug, m in sorted(meta.items()):
        path = next((p for p in (os.path.join(src, f'{slug}{ext}') for ext in ('.jpg', '.png')) if os.path.exists(p)), None)
        if not path or not m.get('license'):
            print('skip', slug)
            continue
        im = Image.open(path).convert('RGB')
        # Sources narrower than the largest size are enlarged with Lanczos and lightly sharpened, so wide screens
        # get a crisp file. This cannot add real detail; a larger original is always better.
        if im.width < WIDTHS[-1]:
            scale = WIDTHS[-1] / im.width
            im = im.resize((WIDTHS[-1], round(im.height * scale)), Image.LANCZOS)
            im = im.filter(ImageFilter.UnsharpMask(radius=1.2 * scale, percent=70, threshold=2))
        widths = list(WIDTHS)
        for w in widths:
            h = round(im.height * w / im.width)
            im.resize((w, h), Image.LANCZOS).save(os.path.join(OUT, f'{slug}-{w}.webp'), 'WEBP', quality=74, method=6)
        tiny = im.resize((24, max(1, round(im.height * 24 / im.width))), Image.LANCZOS)
        buf = io.BytesIO()
        tiny.save(buf, 'WEBP', quality=40)
        entries[slug] = {
            'widths': widths,
            'ratio': round(im.width / im.height, 3),
            'lqip': 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode(),
            'focus': FOCUS.get(slug),
            'supplied': m.get('supplied') or None,
            'credit': {
                'title': credit_title(m['title']),
                'author': m['author'] or 'Unknown author',
                'license': m['license'],
                'licenseUrl': m.get('licenseUrl') or None,
                'source': m.get('page') or None,
            },
        }
        print(slug, widths)
    lines = [
        "import type { PhotoCredit } from './types'",
        '',
        '// Generated by scripts/photos.py. Do not edit by hand.',
        'export const PHOTO_DATA: Record<string, { widths: number[]; ratio: number; lqip: string; focus?: string; supplied?: boolean; credit: PhotoCredit }> = {',
    ]
    for slug, e in entries.items():
        e = {k: v for k, v in e.items() if v is not None}
        e['credit'] = {k: v for k, v in e['credit'].items() if v is not None}
        lines.append(f'  {json.dumps(slug)}: {json.dumps(e, ensure_ascii=False)},')
    lines.append('}')
    open(DATA, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
