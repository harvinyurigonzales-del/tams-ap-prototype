import { expect, test } from '@playwright/test'

test('admin walkthrough A1–A13', async ({ page }) => {
  await page.goto('/admin/dashboard')
  await expect(page.getByText('Please log in as staff to continue.')).toBeVisible()
  await page.getByRole('button', { name: 'Use demo account' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back, Admin!' })).toBeVisible()
  await expect(page.getByText('₱25,092')).toBeVisible()
  await expect(page.getByText('₱31,694')).toBeVisible()
  await page.screenshot({ path: 'test-results/admin-dashboard.png', fullPage: true })

  await page.getByRole('link', { name: /Payments to verify/ }).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: 'BK-2026-0148' }).click()
  const panel = page.getByRole('complementary', { name: 'Booking BK-2026-0148' })
  await expect(panel.getByRole('button', { name: 'Confirm booking' })).toBeDisabled()
  await expect(panel.getByText('Unlocks when at least 50% is verified.')).toBeVisible()

  await panel.getByRole('button', { name: 'View proof' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Verify payment' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Verify payment' }).click()
  await expect(panel.getByText('Partially paid')).toBeVisible()
  await panel.getByRole('button', { name: 'Confirm booking' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm booking' }).click()
  await expect(panel.getByText('Confirmed').first()).toBeVisible()
  await page.screenshot({ path: 'test-results/admin-booking.png', fullPage: true })

  // In-app navigation only: a full page load would reset the in-memory demo.
  const nav = page.getByRole('navigation', { name: 'Admin' })
  await nav.getByRole('link', { name: 'Calendar' }).click()
  await page.getByRole('button', { name: /Oct 17, 2026/ }).click()
  await page.getByRole('listitem').filter({ hasText: 'Van rental · Baler' }).getByRole('button', { name: 'Assign van and driver' }).click()
  const dlg = page.getByRole('dialog')
  await expect(dlg.getByText('Assigned to DEP-BAG-1017 · Oct 17–18').first()).toBeVisible()
  await expect(dlg.getByText('Unavailable until Oct 20')).toBeVisible()
  await expect(dlg.getByText('On leave Oct 16–18')).toBeVisible()
  await page.screenshot({ path: 'test-results/admin-assign.png' })
  await dlg.getByRole('radio', { name: /Van 04/ }).check()
  await dlg.getByRole('radio', { name: /Rogelio Cruz/ }).check()
  await dlg.getByRole('button', { name: 'Save assignment' }).click()
  await expect(page.getByText('Every confirmed trip has a van and driver.')).toHaveCount(0)

  await nav.getByRole('link', { name: 'Reports' }).click()
  await page.getByRole('tab', { name: 'Revenue' }).click()
  await expect(page.getByText('₱27,591').first()).toBeVisible()
  await page.getByRole('tab', { name: 'Bookings' }).click()
  await page.getByLabel('Service').selectOption('SVC-TAG')
  await expect(page.getByText('No records in this period')).toBeVisible()

  await nav.getByRole('link', { name: 'Settings' }).click()
  await page.getByRole('button', { name: 'Reset demo' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Reset demo' }).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByText('Demo reset to the sample data.')).toBeVisible()
  await page.getByRole('link', { name: /Admin demo/ }).click()
  await expect(page.getByRole('heading', { name: 'Staff login' })).toBeVisible()
})

